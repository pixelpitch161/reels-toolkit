GLYPHS = {k: np.array([[c == '#' for c in row] for row in v.split('|')]) for k, v in _G.items()}
ADV = 6   # 5 px glyph + 1 px gap


def text_mask(s, scale=1):
    w = max(1, len(s) * ADV - 1)
    m = np.zeros((7, w), bool)
    for i, ch in enumerate(s):
        g = GLYPHS.get(ch.upper(), GLYPHS[' '])
        m[:, i * ADV:i * ADV + 5] = g
    if scale > 1:
        m = np.repeat(np.repeat(m, scale, 0), scale, 1)
    return m


def dilate(m, r=1):
    h, w = m.shape
    out = np.zeros((h + 2 * r, w + 2 * r), bool)
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            out[r + dy:r + dy + h, r + dx:r + dx + w] |= m
    return out


def stamp(frame, mask, x, y, color, outline=(10, 20, 26), shadow=True, alpha=1.0):
    """Draw mask at top-left (x,y) with a 1px outline and a drop shadow."""
    H, W = frame.shape[:2]
    layers = []
    if outline is not None:
        o = dilate(mask, 1)
        if shadow:
            layers.append((o, x - 1, y + 1, outline))
        layers.append((o, x - 1, y - 1, outline))
    layers.append((mask, x, y, color))
    for m, mx, my, col in layers:
        h, w = m.shape
        x0, y0 = max(0, mx), max(0, my)
        x1, y1 = min(W, mx + w), min(H, my + h)
        if x1 <= x0 or y1 <= y0:
            continue
        sub = m[y0 - my:y1 - my, x0 - mx:x1 - mx]
        region = frame[y0:y1, x0:x1]
        if alpha >= 0.999:
            region[sub] = col
        else:
            region[sub] = (region[sub] * (1 - alpha) + np.array(col) * alpha).astype(np.uint8)


def rich_line(frame, line, cx, y, scale, base_col, hi_col, alt_col, nchars=None, alpha=1.0):
    """Centered line; *words* use hi_col, ~words~ use alt_col. nchars limits
    the typewriter reveal. Returns number of visible characters consumed."""
    plain, cols = [], []
    mode = 0
    for ch in line:
        if ch == '*':
            mode = 0 if mode == 1 else 1
            continue
        if ch == '~':
            mode = 0 if mode == 2 else 2
            continue
        plain.append(ch)
        cols.append(mode)
    total = len(plain)
    width = total * ADV * scale - scale
    x0 = int(round(cx - width / 2))
    show = total if nchars is None else max(0, min(total, nchars))
    i = 0
    while i < show:
        j = i
        while j < show and cols[j] == cols[i]:
            j += 1
        seg = ''.join(plain[i:j])
        col = (base_col, hi_col, alt_col)[cols[i]]
        stamp(frame, text_mask(seg, scale), x0 + i * ADV * scale, y, col, alpha=alpha)
        i = j
    return total
