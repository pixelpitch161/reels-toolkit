def parse(s):
    """'0:2:F#5 ...' -> [(onset16, dur16, midi)]"""
    out = []
    for tok in s.split():
        o, d, n = tok.split(':')
        name, octv = n[:-1], int(n[-1])
        out.append((int(o), int(d), 12 * (octv + 1) + NAMES[name]))
    return out


def bar_notes(n, second_ending=False):
    """(rh, lh) note lists for bar n"""
    rh, lh = BARS[n]
    if second_ending and n in COL8:
        lh = BAR8_LH_SECOND
    return parse(rh), parse(lh)


