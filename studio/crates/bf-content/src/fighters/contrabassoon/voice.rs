/// The Composed arrangement's CONTRABASSOON (sound upgrade, stage 3, S1): its own note with the overtones of the real
/// instrument, the ones it lacks added, a slower start (70 ms to full level) and a quicker stop (a 40 ms fade after
/// its length), nearer the real one's.
pub const REWORK: Rework = Rework {
    fill: FILL,
    correction: CORRECTION,
    speak: 0.07,
    stop: 0.04,
    keep_shape: false,
};

/// The CONTRABASSOON's voice.
#[derive(Clone, Copy, Debug, Default)]
pub struct ContrabassoonVoice;

impl Voice for ContrabassoonVoice {
    fn note(&self, _noise: &mut PpNoise, midi: f64, vel: f64, dur: f64) -> Vec<f64> {
        pp::to_48k(&bassoon_reed(pp::midi_hz(midi), dur, vel, RATTLE))
    }

    fn register(&self) -> (i32, i32) {
        REGISTER
    }

    fn rework(&self) -> Option<&'static Rework> {
        Some(&REWORK)
    }

    fn name(&self) -> &str {
        "CONTRABASSOON"
    }

    fn can_hold(&self, dur: f64) -> bool {
        pp::has_len(dur + TAIL)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_low_note_sounds() {
        let mut noise = PpNoise::start();
        let x = ContrabassoonVoice.note(&mut noise, 34.0, 0.9, 0.4);
        let peak = x.iter().fold(0.0_f64, |a, v| a.max(v.abs()));
        assert!(x.len() > 20_000 && peak > 0.05, "{} samples, peak {peak}", x.len());
    }
}
